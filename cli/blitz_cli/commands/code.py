if TYPE_CHECKING:
    from pathlib import Path

    from blitz_cli.project import Project


class Method(StrEnum):
    get = "get"
    post = "post"
    put = "put"
    patch = "patch"
    delete = "delete"


MUTATING = {Method.post, Method.put, Method.patch, Method.delete}


@dataclass(frozen=True, slots=True)
class DomainInfo:
    name: str
    entity: str
    router: str
    files: dict[str, Path]

    @property
    def error(self) -> str:
        return f"{self.entity}Error"

    @property
    def code_enum(self) -> str:
        return f"{self.entity}ErrorCode"

    @property
    def service(self) -> str:
        return f"{self.entity}Service"

    @property
    def entity_snake(self) -> str:
        return naming.snake(self.entity)

    @property
    def route(self) -> str:
        return self.name.replace("_", "-")


def inspect_domain(proj: Project, name: str) -> DomainInfo:
    """Read the entity and router names from a domain generated by ``blitz``."""
    package = proj.domains_dir / name
    files = {f: package / f"{f}.py" for f in ("errors", "service", "domain")}
    missing = [p for p in files.values() if not p.exists()]
    if not package.is_dir() or missing:
        raise fail(f"no domain {name!r} with errors.py, service.py and domain.py")
    try:
        errors = parse(files["errors"].read_text(), "errors.py")
        domain = parse(files["domain"].read_text(), "domain.py")
    except EditError as exc:
        raise fail(str(exc)) from exc

    def is_code_enum(cls: ast.ClassDef) -> bool:
        return cls.name.endswith("ErrorCode") and any(
            isinstance(b, ast.Name) and b.id == "StrEnum" for b in cls.bases
        )

    code_enum = find_class(errors, is_code_enum)
    if code_enum is None:
        raise fail(f"src/domains/{name}/errors.py has no `<Entity>ErrorCode(StrEnum)`")
    router = next(
        (
            t.id
            for n in domain.body
            if isinstance(n, ast.Assign)
            and isinstance(n.value, ast.Call)
            and isinstance(n.value.func, ast.Name)
            and n.value.func.id == "ResultRouter"
            for t in n.targets
            if isinstance(t, ast.Name)
        ),
        None,
    )
    if router is None:
        raise fail(f"src/domains/{name}/domain.py has no `... = ResultRouter(...)`")
    return DomainInfo(name, code_enum.name.removesuffix("ErrorCode"), router, files)


# ── endpoint ─────────────────────────────────────────────────────────────────


def endpoint(
    ctx: typer.Context,
    domain: Annotated[
        str,
        typer.Argument(
            help="Existing domain package, e.g. orders.", autocompletion=complete_domains
        ),
    ],
    name: Annotated[str, typer.Argument(help="snake_case action, e.g. cancel or search.")],
    method: Annotated[Method, typer.Option(help="HTTP method.")] = Method.post,
    collection: Annotated[
        bool,
        typer.Option(
            "--collection/--item",
            help="Act on the collection (/v1/orders/search) or one item (/v1/orders/{id}/cancel).",
        ),
    ] = False,
    tests: Tests = None,
    dry_run: DryRun = False,
) -> None:
    """Add an endpoint to a domain: a service method, its route and a test.

    The service method is a working stub that loads the entity (or the list) and, for
    POST/PUT/PATCH/DELETE, records an audit event. Put the real rule in it.
    """
    proj = project(ctx)
    info = inspect_domain(proj, domain)
    if not re.fullmatch(r"[a-z][a-z0-9_]*", name):
        raise fail(f"invalid endpoint name {name!r}: use snake_case, e.g. mark_paid")
    id_param = f"{info.entity_snake}_id"
    subject = info.name if collection else info.entity_snake
    route_fn = f"{name}_{subject}"
    action = name.replace("_", "-")
    path = f"/{action}" if collection else f"/{{{id_param}}}/{action}"
    returns = f"list[{info.entity}]" if collection else info.entity
    result_type = f"Result[{returns}, {info.error}]"

    service_text = info.files["service"].read_text()
    domain_text = info.files["domain"].read_text()
    try:
        service_cls = class_named(parse(service_text), info.service)
        if service_cls is None:
            raise fail(f"src/domains/{domain}/service.py has no class {info.service}")
        methods = method_names(service_cls)
        if name in methods:
            raise fail(f"{info.service}.{name} already exists")
        if route_fn in function_names(parse(domain_text)):
            raise fail(f"{route_fn}() already exists in domain.py")
        loader = "list_all" if collection else "get"
        if loader not in methods:
            raise fail(f"{info.service} has no {loader}() to build the stub on; write it by hand")

        audit = method in MUTATING and "_audit_op" in methods
        params = "ctx: RequestContext" if collection else f"{id_param}: str, ctx: RequestContext"
        call = "ctx" if collection else f"{id_param}, ctx"
        resource = "None" if collection else id_param
        lines = [
            f"    async def {name}(self, {params}) -> {result_type}:",
            f'        """{name.replace("_", " ").capitalize()}: replace this stub."""',
        ]
        if audit:
            lines += [
                f"        result = await self.{loader}({call})",
                "        if isinstance(result, Success):",
                f'            await self._audit_op(ctx, "{info.name}.{name}", {resource})',
                "        return result",
            ]
        else:
            lines.append(f"        return await self.{loader}({call})")
        service_text = append_to_class(service_text, info.service, "\n".join(lines))
        service_text = add_import(
            service_text, f"from returns.result import Result{', Success' if audit else ''}"
        )

        route_params = ", ".join(
            [
                *([] if collection else [f"{id_param}: str"]),
                f"svc: {info.service}Dep",
                "ctx: RequestContextDep",
            ]
        )
        status_arg = ", status_code=status.HTTP_204_NO_CONTENT" if method == Method.delete else ""
        route = "\n".join(
            [
                f'@{info.router}.{method.value}("{path}"{status_arg})',
                f"async def {route_fn}({route_params}) -> {result_type}:",
                f"    return await svc.{name}({call})",
            ]
        )
        if method == Method.delete:  # 204 has no body: return Result[None, ...]
            route = route.replace(f"-> {result_type}", f"-> Result[None, {info.error}]")
            route = route.replace(
                f"    return await svc.{name}({call})",
                f"    return (await svc.{name}({call})).map(lambda _: None)",
            )
        # Static paths must precede `/{id}` routes, which would otherwise capture them.
        domain_text = (
            insert_after_assignment(domain_text, info.router, route)
            if collection
            else insert_before_function(domain_text, "make_router", route)
        )
        for line in (
            "from returns.result import Result",
            "from deps import RequestContextDep",
            f"from .dependencies import {info.service}Dep",
            f"from .errors import {info.error}",
            f"from .models import {info.entity}",
            *(["from fastapi import status"] if method == Method.delete else []),
        ):
            domain_text = add_import(domain_text, line)
    except EditError as exc:
        raise fail(f"src/domains/{domain}: {exc}") from exc

    written = [
        write_edit(
            ctx, info.files["service"], service_text, dry_run=dry_run, what=f"{info.service}.{name}"
        ),
        write_edit(
            ctx,
            info.files["domain"],
            domain_text,
            dry_run=dry_run,
            what=f"{method.value.upper()} {path}",
        ),
    ]
    with_tests = config(ctx).tests if tests is None else tests
    services = proj.services_serving(domain)
    if with_tests and services:
        test_path = proj.root / "tests" / "domains" / domain / "integration" / f"test_{name}.py"
        if test_path.exists():
            raise fail(f"{proj.rel(test_path)} already exists")
        url = f"/v1/{info.route}/{action}" if collection else f"/v1/{info.route}/missing/{action}"
        if collection:
            expected = "200" if method != Method.delete else "204"
            body = (
                f'    r = await client.{method.value}("{url}")\n'
                f"    assert r.status_code == {expected}\n"
            )
        else:
            body = (
                f'    r = await client.{method.value}("{url}")\n'
                "    assert r.status_code == 404\n"
                '    assert r.json()["code"] == "not_found"\n'
            )
        test = (
            "import pytest\nfrom fastapi import FastAPI\nfrom httpx import AsyncClient\n\n"
            f"from services.{services[0]}.domains import DOMAINS\n\n\n"
            "@pytest.fixture\ndef app(make_app) -> FastAPI:\n"
            "    return make_app(domains=DOMAINS)\n\n\n"
            f"async def test_{name}(client: AsyncClient) -> None:\n{body}"
        )
        written.append(write_edit(ctx, test_path, test, dry_run=dry_run, what="test"))
        package_init = test_path.parent / "__init__.py"
        if not dry_run and not package_init.exists():
            package_init.write_text("")
    elif with_tests:
        typer.echo(f"  no test: {domain} is not registered with a service")
    if not dry_run:
        finish(ctx, [w for w in written if w], f"fill in {info.service}.{name}, then `make verify`")


# ── error code ───────────────────────────────────────────────────────────────


def error_code(
    ctx: typer.Context,
    domain: Annotated[
        str,
        typer.Argument(
            help="Existing domain package, e.g. orders.", autocompletion=complete_domains
        ),
    ],
    code: Annotated[str, typer.Argument(help="snake_case code, e.g. conflict or out_of_stock.")],
    status: Annotated[int, typer.Option(help="HTTP status the code maps to (400-599).")] = 400,
    dry_run: DryRun = False,
) -> None:
    """Add an error code to a domain and map it to an HTTP status.

    5xx codes never show their message to clients (it is logged instead).
    """
    proj = project(ctx)
    info = inspect_domain(proj, domain)
    if not re.fullmatch(r"[a-z][a-z0-9_]*", code):
        raise fail(f"invalid code {code!r}: use snake_case, e.g. out_of_stock")
    if not 400 <= status <= 599:
        raise fail("--status must be an error status, 400-599")
    text = info.files["errors"].read_text()
    member = code.upper()
    try:
        enum_cls = class_named(parse(text), info.code_enum)
        if enum_cls is None:
            raise fail(f"no class {info.code_enum}")
        existing = {
            t.id
            for n in enum_cls.body
            if isinstance(n, ast.Assign)
            for t in n.targets
            if isinstance(t, ast.Name)
        }
        if member in existing:
            raise fail(f"{info.code_enum}.{member} already exists")
        text = append_to_class(text, info.code_enum, f'    {member} = "{code}"', blank_line=False)
        text = add_dict_entry(text, info.error, "STATUS", f"{info.code_enum}.{member}: {status}")
    except EditError as exc:
        raise fail(f"src/domains/{domain}/errors.py: {exc}") from exc
    written = write_edit(
        ctx, info.files["errors"], text, dry_run=dry_run, what=f"{member} → {status}"
    )
    if not dry_run:
        finish(
            ctx,
            [written] if written else [],
            f"return Failure({info.error}({info.code_enum}.{member}, message)) from the service",
        )
